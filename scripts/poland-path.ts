// Builds src/data/poland.ts: Poland's outline (Natural Earth 1:50m via world-atlas)
// projected to SVG coordinates, plus the projection constants so site markers
// (lon/lat) can be placed on the same map at runtime.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { feature } from "topojson-client";
import type { Topology, GeometryCollection } from "topojson-specification";
import type { Feature, MultiPolygon, Polygon, Position } from "geojson";

const MAP_HEIGHT = 640;
const COS_LAT = Math.cos((52 * Math.PI) / 180); // equirectangular, true scale at 52°N

const topo = JSON.parse(await readFile("node_modules/world-atlas/countries-50m.json", "utf8")) as Topology;
const countries = feature(topo, topo.objects.countries as GeometryCollection);
const poland = countries.features.find((f) => String(f.id) === "616") as Feature<Polygon | MultiPolygon>;
if (!poland) throw new Error("Poland (616) not found in world-atlas");

const polygons: Position[][][] =
  poland.geometry.type === "Polygon" ? [poland.geometry.coordinates] : poland.geometry.coordinates;
const rings = polygons.map((p) => p[0]); // outer rings only

const all = rings.flat();
const minLon = Math.min(...all.map((p) => p[0]));
const maxLat = Math.max(...all.map((p) => p[1]));
const minLat = Math.min(...all.map((p) => p[1]));
const maxLon = Math.max(...all.map((p) => p[0]));
const scale = MAP_HEIGHT / (maxLat - minLat);
const width = (maxLon - minLon) * COS_LAT * scale;

const project = ([lon, lat]: Position) => [(lon - minLon) * COS_LAT * scale, (maxLat - lat) * scale];
const d = rings
  .map((ring) => "M" + ring.map((p) => project(p).map((v) => v.toFixed(1)).join(",")).join("L") + "Z")
  .join("");

await mkdir("src/data", { recursive: true });
await writeFile(
  "src/data/poland.ts",
  `// Generated by scripts/poland-path.ts from world-atlas (Natural Earth 1:50m). Do not edit.
export const POLAND_SIZE = { width: ${width.toFixed(1)}, height: ${MAP_HEIGHT} };
export const POLAND_PATH = "${d}";
export const projectLonLat = (lon: number, lat: number): [number, number] => [
  (lon - ${minLon}) * ${COS_LAT} * ${scale},
  (${maxLat} - lat) * ${scale},
];
`,
);
console.log(`poland.ts: ${rings.length} ring(s), ${all.length} points, ${width.toFixed(0)}×${MAP_HEIGHT}`);
